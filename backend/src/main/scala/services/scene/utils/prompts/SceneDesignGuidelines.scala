       |4. 建筑（题面有建筑时）：≥6 个可辨认构件（窗框/门/檐口/屋顶出檐/烟囱/栏杆/台阶/材质分区/暖光窗）；用 BoxGeometry/ExtrudeGeometry/倒角（Bevel）组合 + 分层贴色 + emissive 暖窗；禁止"盒子 + 三棱柱屋顶"；建筑四面成立：背面与两个侧面必须有墙体或围护，门洞必须开在墙体里、门后是有地板与后墙的室内（相机绕到背面也不能直接看穿到室外）；按米制尺度（开间 3–6m、层高 3–3.6m、门高 2.0–2.4m、窗 0.8–1.6m、台阶 0.15–0.18m）。
       |5. 材质 2–3 种：石/地形 roughness 0.8–0.95、金属 metalness 0.3–0.5 + roughness 0.25–0.4、发光面 emissive 0.2–0.8；至少一处冷暖对比。
       |6. 构件咬合（物理合理）：先定统一的米制尺寸常量，再从常量推出每个构件的位置；门窗不重叠、门底落在地面、窗台不压线脚、立柱/灯杆落地、雨棚/招牌/挑台有支撑、屋顶两端封闭山墙、树和石头不穿进建筑、没有悬在半空的发光板；门后不是空的——门框必须嵌在墙里，墙后是封闭房间（四面墙 + 地板 + 屋顶），从任何方位绕一圈看建筑都不穿帮。

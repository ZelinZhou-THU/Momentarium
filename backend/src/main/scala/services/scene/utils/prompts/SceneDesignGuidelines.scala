  val parentRules: String =
    s"""【设计准则（v3 硬性，写 scenePrompt 时必须落实；scenePrompt 的【场景与空间】【光照与色彩】【避免】要体现这些数字与选择）】
       |D1 构图：三分法 + 前景/中景/远景三层；首屏主体（主地标或主建筑群）占画面 40–60%；写清视觉动线（岸线/步道/光束引导）；首屏下方与上方各 1/4 不得是大片空带（天空可占上 1/4–1/3，但必须有渐变/云层/远山层次）。
       |D2 光影：写明主光方向（例：右前方 35° 低角度）、色温方向（暖 3000–3500K / 冷 7000–9000K）、主光:环境光:轮廓光 ≈ 3:1:1.5；禁止整体近黑或死黑剪影（暗部材质仍要可读），禁止过曝斑块；湿面/水面高光要受控（高光带 0.3–1.5m 宽，亮度不超过主光峰值）。
       |D3 材质：低多边形但至少 2–3 种材质层次（石/木/金属/雾/发光面），给出粗糙度/金属度方向（石 roughness 0.8–0.95；金属 metalness 0.3–0.5 + roughness 0.25–0.4；发光面 emissive 强度 0.2–0.8）；禁止全场景单一材质。
       |D4 色彩：palette 3–5 色必须实际用于天空/主体/材质/光；明确冷暖对比（冷环境 + 暖主光，或反之）与天空渐变方向（如顶部 #0B1020 → 地平线 #F2A65A）；禁止纯灰/纯黑画面。
       |D5 地标与叙事：1 个主地标（灯塔/拱门/桥/门/塔/记忆馆）+ 1–2 个次要素（站牌/长椅/风车/灯箱/台阶）形成记忆焦点；禁止随机几何体或球体堆叠当装饰。主地标优先选常见、结构清楚、容易用低多边形建好的类型（小木屋、凉亭、石桥、风车、灯塔、木栅栏门、长椅与步道）；场景表达的是照片的氛围，不是复刻照片里的建筑。照片里不常见或难以程序化建好的结构（凿进山坡的洞屋、复杂异形建筑等）不要硬复刻，换成能传达同样氛围的常见元素（例：草坡里的圆门洞屋 → 草坡上一间带圆形绿门的小木屋）。
       |D6 尺度与比例：给米制尺度（世界半径 30–60m、主地标高 3–12m、建筑开间 3–6m、层高 3–3.6m、门高 2.0–2.4m、窗 0.8–1.6m、台阶高 0.15–0.18m）；禁止随机大小球体堆叠。
       |D7 水面（有水体时必须写）：水体不得是纯色平面；必须写可读表面——顶点波动/程序化噪声/两层滚动波纹（波长 1.5–4m、振幅 0.03–0.15m、流速 0.15–0.4m/s）+ 岸线泡沫亮带（宽 0.2–0.6m）+ 受控反射条纹（沿主光方向 0.3–1.5m 宽）。
       |D8 建筑/结构（有建筑时必须写）：禁止"盒子+三棱柱"式体量；至少 6–10 个可辨认构件（窗框/门/檐口/屋顶出檐/烟囱/栏杆/台阶/材质分区/室内暖光窗）；低多边形下用挤出/倒角/分层贴色做细节，禁止用贴图糊细节；**每栋建筑必须四面成立**——四面外墙（或有意设计的栏杆/柱廊围护）+ 屋顶闭合 + 门开在墙上、门后有室内空间（地板、后墙、至少一件室内物），背面和侧面与正面同等细致，禁止"只有正面的布景板"。
       |D9 负面约束（avoid 必须覆盖）：水面纯色无纹理；盒子+三角屋顶的简陋建筑；近黑无主光；大片空带；随机球体堆叠；只有正面没有背面的建筑。""".stripMargin


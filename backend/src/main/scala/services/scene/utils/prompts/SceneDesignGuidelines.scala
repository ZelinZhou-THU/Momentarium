    s"""【设计实现要求（v3 硬性，按顺序落实）】
       |1. 先声明并实现「机位 + 主光 + 构图」再搭场景：camera.position/lookAt（fov 45–55）、DirectionalLight（位置/强度 1.0–1.6/暖色）、AmbientLight（0.3–0.6）、轮廓光（冷色 0.4–0.8）。
